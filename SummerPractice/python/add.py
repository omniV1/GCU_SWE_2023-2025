# add two random numbers together

import random 

num1 = random.randint(50, 100)
num2 = random.randint(20, 100)

sum = num1 + num2

print("The sum of", num1, "and", num2, "is", sum)

subtraction = num1 - num2

print("The difference of", num1, "and", num2, "is", subtraction)

multiplication = num1 * num2

print("The product of", num1, "and", num2, "is", multiplication)

division = num1 / num2

print("The quotient of", num1, "and", num2, "is", division)

modulus = num1 % num2

print("The modulus of", num1, "and", num2, "is", modulus)

exponent = num1 ** num2

print("The exponent of", num1, "and", num2, "is", exponent)

floor_division = num1 // num2

print("The floor division of", num1, "and", num2, "is", floor_division)

